"""Apply 4-candidates.json (Blizzard localization mining) to the merged lexicon.

Runs after merge_candidates.py, on the lexicon that merge produced, with the same policy: high and medium
confidence only; a fix applies only while its "old" value still matches, and its evidence is merged into
the entry; anything else is logged. Appends a section to merge-log.md. From the repo root:
  python3 research/2026-11-revival/scripts/apply_localization.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from merge_candidates import APPLY, LEX, LOG, RES, key, merge_evidence  # noqa: E402

MARK = "## Localization mining (4-candidates.json)"


def apply_fixes(lexicon, candidates):
    """Apply the candidates to the lexicon in place; return the applied, stale and held labels."""
    applied, stale, held = [], [], []
    for c in candidates:
        label = f"{c['action']} {c['word']}{'.' + c['field'] if c.get('field') else ''} ({c['confidence']})"
        if c["confidence"] not in APPLY or c["action"] != "fix":
            held.append(label)
            continue
        hits = [e for e in lexicon if key(e["word"]) == key(c["word"])]
        if len(hits) != 1 or hits[0].get(c["field"]) != c.get("old"):
            stale.append(label)
            continue
        entry = hits[0]
        entry[c["field"]] = c["new"]
        entry["evidence"] = merge_evidence(entry.get("evidence"), c.get("evidence"))
        applied.append(label)
    return applied, stale, held


def main():
    with open(LEX, encoding="utf-8") as fh:
        lexicon = json.load(fh)
    with open(os.path.join(RES, "4-candidates.json"), encoding="utf-8") as fh:
        candidates = json.load(fh)
    with open(LOG, encoding="utf-8") as fh:
        if MARK in fh.read():
            sys.exit("4-candidates.json is already applied (see merge-log.md); nothing to do.")

    applied, stale, held = apply_fixes(lexicon, candidates)

    with open(LEX, "w", encoding="utf-8") as fh:
        json.dump(lexicon, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    with open(LOG, "a", encoding="utf-8") as fh:
        fh.write(f"\n{MARK}\n\nGenerated by `scripts/apply_localization.py`.\n\n")
        for title, rows in (("Applied", applied), ("Stale (old value no longer matches)", stale),
                            ("Held back (low confidence or not a fix)", held)):
            fh.write(f"### {title} ({len(rows)})\n\n")
            fh.writelines(f"{i}. {r}\n" for i, r in enumerate(rows, 1))
            fh.write("\n")
    print(f"applied {len(applied)}, stale {len(stale)}, held {len(held)}")
    for r in stale:
        print("  stale:", r)


if __name__ == "__main__":
    main()
