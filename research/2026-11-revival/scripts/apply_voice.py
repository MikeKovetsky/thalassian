"""Apply 5-candidates.json (Skyborne voice transcription) to the lexicon.

Runs after apply_localization.py, with the same policy: high and medium confidence only; a fix applies
only while its "old" value still matches, and its evidence is merged into the entry. An add applies only
when no entry has the same word and source. Everything else is logged, and an action other than add or fix
is refused. Appends a section to merge-log.md.
From the repo root:
  python3 research/2026-11-revival/scripts/apply_voice.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from apply_localization import apply_fixes  # noqa: E402
from merge_candidates import APPLY, LEX, LOG, RES, key  # noqa: E402

MARK = "## Voice transcription (5-candidates.json)"
ENTRY_FIELDS = ("word", "translation", "pos", "canon", "root", "notes", "source", "canon_basis",
                "confidence", "method", "evidence")


def apply_adds(lexicon, candidates):
    """Append the new entries in place; return the added, duplicate and held labels. Fixes are left to
    apply_fixes; any other action is refused, because neither function would log it."""
    added, duplicate, held = [], [], []
    for c in candidates:
        if c["action"] == "fix":
            continue
        if c["action"] != "add":
            raise ValueError(f"{c['word']}: apply_voice.py applies only adds and fixes, not {c['action']!r}")
        if c.get("canon"):
            raise ValueError(f"{c['word']}: a voice line carries no Blizzard gloss, so a voice add is never canon")
        label = f"add {c['word']} ({c['confidence']})"
        if c["confidence"] not in APPLY:
            held.append(label)
        elif any(key(e["word"]) == key(c["word"]) and e.get("source") == c["source"] for e in lexicon):
            duplicate.append(label)
        else:
            entry = dict(c, canon_basis="inferred")
            lexicon.append({k: entry[k] for k in ENTRY_FIELDS})
            added.append(label)
    return added, duplicate, held


def main():
    with open(LEX, encoding="utf-8") as fh:
        lexicon = json.load(fh)
    with open(os.path.join(RES, "5-candidates.json"), encoding="utf-8") as fh:
        candidates = json.load(fh)
    with open(LOG, encoding="utf-8") as fh:
        if MARK in fh.read():
            sys.exit("5-candidates.json is already applied (see merge-log.md); nothing to do.")

    applied, stale, held = apply_fixes(lexicon, [c for c in candidates if c["action"] == "fix"])
    added, duplicate, held_adds = apply_adds(lexicon, candidates)

    with open(LEX, "w", encoding="utf-8") as fh:
        json.dump(lexicon, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    with open(LOG, "a", encoding="utf-8") as fh:
        fh.write(f"\n{MARK}\n\nGenerated by `scripts/apply_voice.py`.\n\n")
        for title, rows in (("Added", added), ("Fixes applied", applied),
                            ("Stale (old value no longer matches, or the word already exists)", stale + duplicate),
                            ("Held back (low confidence)", held + held_adds)):
            fh.write(f"### {title} ({len(rows)})\n\n")
            fh.writelines(f"{i}. {r}\n" for i, r in enumerate(rows, 1))
            fh.write("\n")
    print(f"added {len(added)}, fixes {len(applied)}, stale {len(stale) + len(duplicate)}, "
          f"held {len(held) + len(held_adds)}")
    for r in stale + duplicate:
        print("  stale:", r)


if __name__ == "__main__":
    main()
